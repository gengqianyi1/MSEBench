#!/usr/bin/env bash
# Bootstrap the public Harbor runner environment on Ubuntu 24.04.
# Usage: sudo bash scripts/bootstrap_linux.sh /absolute/path/to/benchmark
# It installs only runner prerequisites; each task builds scientific dependencies
# from its own Dockerfile. No model credential is read or written.

set -Eeuo pipefail
BENCH_DIR="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
HARBOR_VENV="${HARBOR_VENV:-$BENCH_DIR/.venv-harbor}"
SKIP_DOCKER_TEST="${SKIP_DOCKER_TEST:-0}"
fail() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "==> $*"; }

[ "$(id -u)" -eq 0 ] || fail "Run with sudo so apt and Docker can be configured."
[ -f "$BENCH_DIR/pyproject.toml" ] || fail "Not a benchmark root: $BENCH_DIR"
. /etc/os-release
[ "${ID:-}" = ubuntu ] || fail "This bootstrap supports Ubuntu only (detected ${ID:-unknown})."
[ "${VERSION_ID:-}" = 24.04 ] || fail "Ubuntu 24.04 is required (detected ${VERSION_ID:-unknown})."

info "Installing host prerequisites"
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends ca-certificates curl git gnupg python3.12 python3.12-venv python3-pip

if ! command -v docker >/dev/null 2>&1; then
  info "Installing Docker Engine from Docker's official Ubuntu repository"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
  chmod a+r /etc/apt/keyrings/docker.gpg
  printf '%s\n' "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" > /etc/apt/sources.list.d/docker.list
  apt-get update
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
if command -v systemctl >/dev/null 2>&1 && systemctl list-unit-files docker.service >/dev/null 2>&1; then systemctl enable --now docker; fi

info "Creating Harbor virtual environment: $HARBOR_VENV"
python3.12 -m venv "$HARBOR_VENV"
"$HARBOR_VENV/bin/python" -m pip install --upgrade pip
"$HARBOR_VENV/bin/python" -m pip install 'harbor==0.21.0' 'jsonschema>=4.23.0' 'pyyaml>=6.0.2'
"$HARBOR_VENV/bin/python" -m pip install -e "$BENCH_DIR"

RUN_USER="${SUDO_USER:-root}"
if [ "$RUN_USER" != root ]; then
  usermod -aG docker "$RUN_USER"
  chown -R "$RUN_USER":"$RUN_USER" "$HARBOR_VENV"
fi
cat > "$BENCH_DIR/.harbor-env.example" <<EOF
# Generated by scripts/bootstrap_linux.sh. Copy outside this repository if editing.
export BENCH="$BENCH_DIR"
export JOBS="\$BENCH/jobs"
export PATH="$HARBOR_VENV/bin:\$PATH"
export PYTHONPATH="\$BENCH"
# Put model credentials only in a separate permission-restricted env file.
EOF

info "Checking runner installation"
"$HARBOR_VENV/bin/harbor" --version
"$HARBOR_VENV/bin/python" "$BENCH_DIR/scripts/validate_structure.py" "$BENCH_DIR/tasks"
if [ "$SKIP_DOCKER_TEST" = 1 ]; then
  info "Docker smoke test skipped (SKIP_DOCKER_TEST=1)."
elif docker info >/dev/null 2>&1; then
  info "Checking Docker image pull/run capability"
  docker run --rm alpine:3.20 true
else
  cat >&2 <<'EOF'
Docker is installed but unavailable to this shell. On native Ubuntu, log out/in after
the docker-group change, then run docker info. On WSL with Docker Desktop, enable
Docker WSL integration for this distribution and rerun the smoke test.
EOF
  exit 2
fi
cat <<EOF

Bootstrap completed. Open a new login shell (or run newgrp docker), then:
  source "$BENCH_DIR/.harbor-env.example"
Do not run Tasks 04--06 in a common-agent batch until their protocol remediation is released.
EOF
