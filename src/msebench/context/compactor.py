"""Shared LLM-summary context compaction for the MatBench agent harnesses.

Replaces destructive hard-truncation with two layers:
  1. deterministic per-message hygiene (size caps, reasoning policy, pairing), and
  2. when the wire-ready prompt exceeds the token budget, an LLM digest of the
     older "middle" turns (generated by the model under test) inserted as a
     single `system` sentinel message.

The raw conversation log is never destroyed: `project()` returns a per-turn
projection while the caller keeps appending to its append-only list.
"""
from __future__ import annotations

import json
import os


def _env_int(name, default):
    """Env-overridable integer knob (invalid values fall back to default)."""
    try:
        return int(os.environ.get(name) or default)
    except (TypeError, ValueError):
        return default


DIGEST_SENTINEL = (
    "[HARNESS CONTEXT DIGEST - earlier turns summarized by harness tooling; "
    "not a user message]"
)
ELISION_NOTICE = (
    "[HARNESS: {count} older events elided at turn {turn}; "
    "live recent context retained]"
)

# Per-message hygiene caps. Tool bodies and retained reasoning are the two
# largest transcript-growth terms for effort=max models; tighter caps slow
# the growth and postpone the digest cycle. Defaults re-tuned 2026-09-20:
# TOOL_LIMIT 20000->8000, REASONING_KEEP_TURNS 2->1, REASONING_LIMIT 20000->8000.
TOOL_LIMIT = _env_int("CHEMBENCH_CONTEXT_TOOL_LIMIT", 8000)
OTHER_LIMIT = _env_int("CHEMBENCH_CONTEXT_OTHER_LIMIT", 12000)
REASONING_KEEP_TURNS = _env_int("CHEMBENCH_CONTEXT_REASONING_TURNS", 0)
REASONING_LIMIT = _env_int("CHEMBENCH_CONTEXT_REASONING_LIMIT", 8000)
REASONING_DIGEST_CHARS = _env_int("CHEMBENCH_CONTEXT_REASONING_DIGEST_CHARS", 16000)

# Digest trigger + retained tail (in estimated tokens). BUDGET_TOKENS is the
# raw-transcript size at which the middle starts being digested; while under
# it the full transcript rides the wire, so keep headroom for the provider
# context window and the max_tokens output reserve. Defaults 2026-09-20:
# BUDGET 100000->120000, TAIL 40000->50000.
BUDGET_TOKENS = _env_int("CHEMBENCH_CONTEXT_BUDGET_TOKENS", 120000)
PANIC_TOKENS = _env_int("CHEMBENCH_CONTEXT_PANIC_TOKENS", 200000)
TAIL_TOKENS = _env_int("CHEMBENCH_CONTEXT_TAIL_TOKENS", 50000)
MAX_DIGESTS = _env_int("CHEMBENCH_CONTEXT_MAX_DIGESTS", 20)
# Hard cap on total digest LLM calls per run (task02 2026-09-20: 212 digest
# calls out of 496 total burned hours of quota). Past the cap the compactor
# degrades to deterministic elision instead of calling the model again.
MAX_DIGEST_CALLS = _env_int("CHEMBENCH_CONTEXT_MAX_DIGEST_CALLS", 60)
SUMMARY_MAX_TOKENS = 8192
SUMMARY_MAX_CHARS = 6000
CHARS_PER_TOKEN = 3.5

SUMMARY_SYSTEM = (
    "You are a context-compression utility embedded in a benchmark harness. "
    "Output ONLY a compact digest of the supplied agent-history segment; "
    f"at most {SUMMARY_MAX_CHARS} characters; no preamble, no commentary."
)
SUMMARY_INSTRUCTION = (
    "Compress the agent-history segment below into a terse digest so the agent "
    "can continue its task. Preserve, in priority order:\n"
    "1. exact identifiers (file paths, tool/function names, SMILES, IDs, URLs) verbatim;\n"
    "2. the task objective, constraints, and evaluation requirements;\n"
    "3. established facts, environment state, and tool contracts already learned;\n"
    "4. decisions made, plans, and the next intended action;\n"
    "5. errors and failures (condensed) so they are not repeated;\n"
    "6. numerical results with exact values and units.\n"
    "Discard verbose tool output bodies and reasoning prose. "
    f"Hard limit {SUMMARY_MAX_CHARS} characters."
)
SUMMARY_RETRY_NUDGE = (
    "\n\nThe previous attempt failed (empty or over-long). Be maximally terse: "
    "at most 3000 characters, telegraphic bullets only, no prose."
)


def _payload(item):
    size = len(str(item.get("content") or ""))
    calls = item.get("tool_calls")
    if calls:
        size += len(json.dumps(calls, ensure_ascii=False))
    return size


def estimate_tokens(items):
    return sum(_payload(m) for m in items) / CHARS_PER_TOKEN


def _head_tail(text, limit):
    if len(text) <= limit:
        return text
    half = max(1, limit // 2)
    return text[:half] + "\n...[harness: reasoning middle elided]...\n" + text[-half:]


def hygiene(messages):
    """Deterministic caps + reasoning policy + assistant/tool pairing repair."""
    with_reasoning = [
        i for i, m in enumerate(messages)
        if m.get("role") == "assistant" and m.get("reasoning_content")
    ]
    # NOTE: list[-0:] == list[:] -- a zero KEEP_TURNS must select NOTHING,
    # not everything. Guard the slice explicitly.
    keep = (set(with_reasoning[-REASONING_KEEP_TURNS:])
            if with_reasoning and REASONING_KEEP_TURNS > 0 else set())
    compact = []
    for index, msg in enumerate(messages):
        item = dict(msg)
        reasoning = item.get("reasoning_content")
        if index not in keep:
            item.pop("reasoning_content", None)
        elif isinstance(reasoning, str) and len(reasoning) > REASONING_LIMIT:
            item["reasoning_content"] = (
                reasoning[:REASONING_LIMIT] + "\n...[truncated for context budget]"
            )
        content = item.get("content")
        if isinstance(content, str):
            limit = TOOL_LIMIT if item.get("role") == "tool" else OTHER_LIMIT
            if len(content) > limit:
                item["content"] = content[:limit] + "\n...[truncated for context budget]"
        compact.append(item)
    pending = set()
    for index, item in enumerate(list(compact)):
        if item.get("role") == "assistant" and item.get("tool_calls"):
            pending = {
                call.get("id") for call in item.get("tool_calls", [])
                if isinstance(call, dict) and call.get("id")
            }
            continue
        if item.get("role") != "tool":
            continue
        call_id = item.get("tool_call_id")
        if call_id in pending:
            pending.discard(call_id)
            continue
        recovered = dict(item)
        recovered.pop("tool_call_id", None)
        recovered["role"] = "user"
        recovered["content"] = "Tool result (context recovery): " + str(item.get("content", ""))
        compact[index] = recovered
    return compact


def _split_head_groups(messages):
    """Return (head, groups): head = leading system/user run, groups = atomic
    (assistant + its contiguous tool outputs) units."""
    head = []
    index = 0
    while index < len(messages) and messages[index].get("role") in ("system", "user"):
        head.append(messages[index])
        index += 1
    groups = []
    current = None
    for item in messages[index:]:
        if item.get("role") == "assistant":
            if current:
                groups.append(current)
            current = [item]
        elif current is None:
            head.append(item)
        else:
            current.append(item)
            if item.get("role") != "tool":
                groups.append(current)
                current = None
    if current:
        groups.append(current)
    return head, groups


class ContextCompactor:
    """Per-run projection with an LLM digest, falling back to deterministic truncation."""

    def __init__(self, summarize, budget_tokens=BUDGET_TOKENS):
        self.summarize = summarize
        self.budget_tokens = budget_tokens
        self.digests = []
        self.degraded = False
        self.digest_calls = 0
        self.digested_groups = 0
        self.turn = 0
        self.prompt_tokens = None
        self.prompt_chars = None
        self._reason_digest_cache = {}

    def observe(self, usage):
        """Record the real prompt_tokens of the last request to sharpen the estimate."""
        tokens = None
        if isinstance(usage, dict):
            tokens = usage.get("prompt_tokens")
        if isinstance(tokens, int) and tokens > 0:
            self.prompt_tokens = tokens
            self.prompt_chars = None

    def _digest_oversized_reasoning(self, messages):
        indices = [
            i for i, m in enumerate(messages)
            if m.get("role") == "assistant" and isinstance(m.get("reasoning_content"), str)
        ]
        targets = [
            i for i in (indices[-REASONING_KEEP_TURNS:] if REASONING_KEEP_TURNS > 0 else [])
            if len(messages[i]["reasoning_content"]) > REASONING_DIGEST_CHARS
        ]
        if not targets:
            return messages
        out = list(messages)
        for index in targets:
            digest = self._reason_digest_cache.get(index)
            if digest is None:
                blob = messages[index]["reasoning_content"]
                try:
                    digest = self.summarize(
                        "Summarize this agent reasoning trace in <=1500 characters; keep exact "
                        "identifiers, decisions, and the next intended action:\n"
                        + blob[:REASONING_DIGEST_CHARS]
                    )
                except Exception:
                    digest = None
                if not isinstance(digest, str) or not digest.strip():
                    digest = _head_tail(blob, REASONING_LIMIT)
                else:
                    digest = "harness reasoning digest: " + digest.strip()[:3000]
                self._reason_digest_cache[index] = digest
            item = dict(out[index])
            item["reasoning_content"] = digest
            out[index] = item
        return out

    def _estimate(self, items):
        total = sum(_payload(m) for m in items)
        if self.prompt_chars is not None and total >= self.prompt_chars:
            return self.prompt_tokens + (total - self.prompt_chars) / CHARS_PER_TOKEN
        return total / CHARS_PER_TOKEN

    def _assemble(self, head, groups, tail_start, notice=None):
        wire = []
        for item in head:
            wire.append(dict(item))
        for text in self.digests:
            wire.append({"role": "system", "content": DIGEST_SENTINEL + "\n" + text})
        if notice:
            wire.append({"role": "system", "content": notice})
        for group in groups[tail_start:]:
            for item in group:
                wire.append(dict(item))
        return hygiene(wire)

    def project(self, messages):
        self.turn += 1
        clean = hygiene(self._digest_oversized_reasoning(messages))
        self.prompt_chars = sum(_payload(m) for m in clean) if self.prompt_tokens else None
        head, groups = _split_head_groups(clean)
        tail_start = self._tail_start(head, groups)
        middle = groups[self.digested_groups:tail_start]
        if not middle:
            return self._assemble(head, groups, tail_start)
        if not self.degraded and self._estimate(clean) <= PANIC_TOKENS and self.digest_calls < MAX_DIGEST_CALLS:
            try:
                digest = self._summarize_groups(head, middle)
                self._push_digest(digest)
                self.digest_calls += 1
                self.digested_groups = tail_start
                return self._assemble(head, groups, tail_start)
            except Exception:
                self.degraded = True
        count = sum(len(group) for group in middle)
        self.digested_groups = tail_start
        return self._assemble(
            head, groups, tail_start,
            notice=ELISION_NOTICE.format(count=count, turn=self.turn),
        )

    def _tail_start(self, head, groups):
        flat = [m for group in groups for m in group]
        if estimate_tokens(head) + estimate_tokens(flat) <= self.budget_tokens:
            return 0
        used = 0.0
        start = len(groups)
        while start > 0:
            group_tokens = estimate_tokens(groups[start - 1])
            if used + group_tokens > TAIL_TOKENS and len(groups) - start >= 2:
                break
            used += group_tokens
            start -= 1
        return start

    def _push_digest(self, digest):
        if not isinstance(digest, str) or not digest.strip():
            raise RuntimeError("empty digest")
        self.digests.append(digest.strip()[:SUMMARY_MAX_CHARS])
        while len(self.digests) > MAX_DIGESTS:
            merged = self._merge_digests(self.digests[0], self.digests[1])
            self.digests = [merged] + self.digests[2:]

    def _merge_digests(self, first, second):
        try:
            merged = self.summarize(
                "Merge these two digests into one, <=3000 characters, "
                "keep exact identifiers:\n" + first + "\n---\n" + second
            )
            if isinstance(merged, str) and merged.strip():
                return merged.strip()[:SUMMARY_MAX_CHARS]
        except Exception:
            pass
        return (first + "\n---\n" + second)[:SUMMARY_MAX_CHARS]

    def _summarize_groups(self, head, middle):
        head_text = "\n".join(
            f"{m.get('role')}: {str(m.get('content') or '')[:4000]}" for m in head
        )
        parts = []
        for group in middle:
            for item in group:
                role = item.get("role")
                body = str(item.get("content") or "")
                if role == "tool" and len(body) > 8000:
                    body = body[:8000] + f"\n...(elided {len(body) - 8000} chars)"
                calls = item.get("tool_calls")
                if calls:
                    body += " | tool_calls=" + json.dumps(calls, ensure_ascii=False)[:2000]
                parts.append(f"{role}: {body}")
        user = (
            SUMMARY_INSTRUCTION
            + "\n\n## Task context (grounding)\n" + head_text
            + "\n\n## Agent-history segment to summarize\n" + "\n".join(parts)
        )
        messages = [
            {"role": "system", "content": SUMMARY_SYSTEM},
            {"role": "user", "content": user},
        ]
        result = self.summarize(messages)
        if isinstance(result, str) and result.strip():
            return result
        retried = self.summarize(
            [messages[0], {"role": "user", "content": user + SUMMARY_RETRY_NUDGE}]
        )
        if not isinstance(retried, str) or not retried.strip():
            raise RuntimeError("summary unavailable")
        return retried
