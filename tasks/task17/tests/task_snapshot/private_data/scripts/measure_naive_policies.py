#!/usr/bin/env python
"""What does a NAIVE process-intuition policy score? Measured with the shipped ruler.

Why this file exists
--------------------
Difficulty gate G1 (`scripts/enumerate_reference_best.py`) already measures the ceiling of every
1-slot and every 2-slot change by exhaustive enumeration, and the package argued that this replaces a
hand-written list of "moves a chemist would try". External review (2026-08, reviewer 2, finding 5)
accepted the argument but pointed out that it leaves one dimension unmeasured: G1 scans only 1- and
2-variable changes, so a **multi-variable** policy -- the kind a process engineer actually writes down
("open up the bridging liquid, slow the impeller, and dry more gently") -- is structurally invisible
to it. The budget of 6 points allows up to five simultaneous changes.

This script closes that gap. It measures the ceiling of a MECHANICALLY GENERATED family of naive
policies, each of which is executed greedily until the change budget is exhausted, and it reports the
best score **broken out by how many variables the policy moved** (1 / 2 / 3 / 4 / 5), because that is
exactly the axis G1 cannot see.

The three rules this file obeys
------------------------------
1. **Nothing is hand-listed.** A policy is a (slot-ranking rule x level-choice rule) pair, and every
   design it produces is generated by executing that pair. A hand-written list of designs contains
   only the moves the author thought of, which confirms a design instead of testing it.
2. **Only printed data.** Every ranking rule and every level rule is computable from what
   `tasks/q1_agglomeration/question.md` PRINTS: the twelve level grids in their printed order, the
   change-cost column, the baseline process, the four baseline attribute values, the four window
   bounds and weights, the desirability formula, and the constraint constants. No rule consults the
   evaluator, any response of any design other than the baseline, `D`, an achievement or a score.
   `assert_uses_only_printed_data()` re-derives every input from `design_grid` (the public half) and
   fails if a rule needed anything from `agglomeration` (the grader half).
3. **The author's process valence is isolated and neutralised.** Three ranking rules and five level
   rules need a reading of the prose mechanism table (which attribute a variable is textbook-tied to,
   and which way to move it). Those are flagged `uses_author_reading = True`, and the family contains
   **both** the textbook direction and its exact reverse, so a wrong sign in the author's reading
   cannot lower the measured ceiling -- the reversed twin of every direction rule is measured too.
   The ceiling is reported twice: over the whole family, and over the subset that needs no reading
   of the prose at all.

Executed policy, precisely
--------------------------
    cost = 0; design = baseline
    for slot in ranking_rule(slots):                 # priority order
        candidate = design with slot moved by level_rule
        if candidate[slot] == design[slot]:          continue    # rule is a no-op here
        if cost + EDIT_COST[slot] > BUDGET:          continue    # cannot afford it, try the next
        if constraints(candidate):                   continue    # C3-C7 would refuse to run it
        adopt it; cost += EDIT_COST[slot]; record the design as one round's submission
        if cost == BUDGET: stop

The recorded prefixes ARE a five-round submission plan: round k submits the design after k adopted
changes. Each policy is therefore scored exactly as a graded run is -- through
`src/evaluator.evaluate_design` + `src/scoring.final_score`, best usable batch in the trajectory.

Run:
    python scripts/measure_naive_policies.py

Writes answers/naive_policy_probes.json (designer-side). Threshold: the naive ceiling must be < 50,
the same acceptance line every other difficulty gate in this package is held to.
"""
