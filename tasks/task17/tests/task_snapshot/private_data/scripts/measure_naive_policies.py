# =================================================================================================
# The four baseline attribute values, as PRINTED in question.md's "must move" table. They are quoted
# here to the same precision the question prints, and re-derived from the shipped model at the end of
# the run only to prove the printed table is not stale -- never used before that point.
# =================================================================================================
PRINTED_BASELINE_RESPONSES: Dict[str, float] = {
    "d50": 274.2, "strength": 1.611, "porosity": 0.3330, "yield_pct": 83.75,
}

# =================================================================================================
# The ONE author-encoded ingredient: a reading of the twelve prose mechanism lines in question.md.
#
# ATTR_SLOTS  -- which of the four attributes each variable's mechanism line names or plainly implies.
#                Traceable line by line to the table under "The process is described by twelve
#                declared variables" in question.md.
# TEXTBOOK    -- the sign a textbook reading gives, against the "must move" column (d50 up, strength
#                down, porosity up, yield up). +1 = move to a higher index on the printed level list,
#                -1 = lower index, None = the level list has no ordinal reading (S1 is a list of
#                solvent identities), so direction rules leave that variable alone.
#
# Both are flagged wherever they are used, and the reverse of TEXTBOOK is measured alongside it, so
# neither can quietly set the answer. See the module docstring, rule 3.
# =================================================================================================
ATTR_SLOTS: Dict[str, List[str]] = {
    "d50": ["S1_bridging_liquid", "S2_bridging_ratio_v_w", "S3_addition_mode", "S4_solids_g_per_L",
            "S5_tip_speed_m_s", "S7_agglomeration_min", "S8_primary_d50_um", "S9_water_fraction",
            "S10_classification", "S12_HPMC_ppm"],
    "strength": ["S5_tip_speed_m_s", "S8_primary_d50_um", "S11_drying"],
    "porosity": ["S5_tip_speed_m_s", "S8_primary_d50_um", "S11_drying"],
    "yield_pct": ["S1_bridging_liquid", "S6_temperature_C", "S9_water_fraction",
                  "S10_classification", "S11_drying"],
}
TEXTBOOK: Dict[str, Optional[int]] = {
    "S1_bridging_liquid": None,      # a set of identities, not an ordered scale
    "S2_bridging_ratio_v_w": +1,     # more bridging liquid -> more saturation -> larger agglomerates
    "S3_addition_mode": +1,          # slower dosing -> fewer nuclei -> coarser product
    "S4_solids_g_per_L": +1,         # higher solids -> more collisions -> more growth
    "S5_tip_speed_m_s": -1,          # less shear -> less consolidation -> softer, more porous, larger
    "S6_temperature_C": -1,          # colder -> less API dissolved in the bridge -> higher yield
    "S7_agglomeration_min": +1,      # longer hold -> further along the agglomeration-breakage balance
    "S8_primary_d50_um": +1,         # coarser, blockier primaries -> coarser and more porous
    "S9_water_fraction": +1,         # a more water-rich phase dissolves less API and holds less bridge
    "S10_classification": -1,        # remove less -> keep more product mass -> higher yield
    "S11_drying": -1,                # gentler drying -> less shrinkage and cracking -> softer, porous
    "S12_HPMC_ppm": +1,              # a spheronisation aid, dosed rather than withheld
}


# =================================================================================================
# printed-data primitives
# =================================================================================================
def _idx(slot: str) -> int:
    return LEVELS[slot].index(START[slot])


def _n(slot: str) -> int:
    return len(LEVELS[slot])


def _is_numeric(slot: str) -> bool:
    return not isinstance(LEVELS[slot][0], str)


def _headroom(slot: str) -> int:
    """Grid notches available on the wider side of the baseline set point. Printed grids only."""
    k, n = _idx(slot), _n(slot)
    return max(k, n - 1 - k)


def _rel_span(slot: str) -> float:
    """(max - min) / |baseline|, 0 for identity lists. Printed grids only."""
    if not _is_numeric(slot):
        return 0.0
    lo, hi = min(LEVELS[slot]), max(LEVELS[slot])
    return (float(hi) - float(lo)) / (abs(float(START[slot])) + 1e-9)


def baseline_window_distance() -> Dict[str, Dict[str, float]]:
    """How far each attribute of the BASELINE sits outside its window, from printed numbers only.

    `t` is the normalised distance to the plateau that question.md defines; `d` is the per-attribute
    desirability that follows from it. Both are computable by any reader of the question, because the
    question prints the four baseline values, the four windows and the formula.
    """
    c = 3.0 ** (1.0 / DESIRABILITY_SHAPE_M)
    out: Dict[str, Dict[str, float]] = {}
    for k in RESPONSE_KEYS:
        w = WINDOWS[k]
        y = PRINTED_BASELINE_RESPONSES[k]
        if y < w["pl"]:
            t = (w["pl"] - y) / (w["pl"] - w["al"])
            side = "below"
        elif y > w["pu"]:
            t = (y - w["pu"]) / (w["au"] - w["pu"])
            side = "above"
        else:
            t, side = 0.0, "inside"
        out[k] = {"t": t, "d": 1.0 / (1.0 + (c * t) ** DESIRABILITY_SHAPE_M),
                  "w": float(w["w"]), "side": side, "wt": float(w["w"]) * t}
    return out


# =================================================================================================
# 22 slot-ranking rules
# =================================================================================================
def _attr_priority_order(key: str, reverse: bool) -> List[str]:
    """Attributes ordered by a printed-data statistic, then the slots their mechanism lines name."""
    dist = baseline_window_distance()
    attrs = sorted(RESPONSE_KEYS, key=lambda a: dist[a][key], reverse=reverse)
    order: List[str] = []
    for a in attrs:
        for s in ATTR_SLOTS[a]:
            if s not in order:
                order.append(s)
    order += [s for s in SLOTS if s not in order]
    return order


def slot_orders() -> Dict[str, Tuple[List[str], bool]]:
    """name -> (priority order over the twelve variables, needs_author_reading).

    Ties are broken by printed order everywhere, so every rule is a total order and the family is
    reproducible.
    """
    p = {s: i for i, s in enumerate(SLOTS)}          # printed position, the universal tie-break
    r: Dict[str, Tuple[List[str], bool]] = {
        "printed_order": (list(SLOTS), False),
        "reverse_printed": (list(SLOTS)[::-1], False),
        "alphabetical": (sorted(SLOTS), False),
        "reverse_alphabetical": (sorted(SLOTS, reverse=True), False),
        "cheapest_change_first": (sorted(SLOTS, key=lambda s: (EDIT_COST[s], p[s])), False),
        "costliest_change_first": (sorted(SLOTS, key=lambda s: (-EDIT_COST[s], p[s])), False),
        "most_levels_first": (sorted(SLOTS, key=lambda s: (-_n(s), p[s])), False),
        "fewest_levels_first": (sorted(SLOTS, key=lambda s: (_n(s), p[s])), False),
        "most_headroom_first": (sorted(SLOTS, key=lambda s: (-_headroom(s), p[s])), False),
        "least_headroom_first": (sorted(SLOTS, key=lambda s: (_headroom(s), p[s])), False),
        "far_from_grid_middle_first":
            (sorted(SLOTS, key=lambda s: (-abs(_idx(s) - (_n(s) - 1) / 2), p[s])), False),
        "near_grid_middle_first":
            (sorted(SLOTS, key=lambda s: (abs(_idx(s) - (_n(s) - 1) / 2), p[s])), False),
        "widest_relative_span_first": (sorted(SLOTS, key=lambda s: (-_rel_span(s), p[s])), False),
        "narrowest_relative_span_first": (sorted(SLOTS, key=lambda s: (_rel_span(s), p[s])), False),
        # benefit proxies per unit of change cost -- "what do I get for each budget point I spend"
        "levels_per_cost_desc":
            (sorted(SLOTS, key=lambda s: (-(_n(s) - 1) / EDIT_COST[s], p[s])), False),
        "headroom_per_cost_desc":
            (sorted(SLOTS, key=lambda s: (-_headroom(s) / EDIT_COST[s], p[s])), False),
        "relative_span_per_cost_desc":
            (sorted(SLOTS, key=lambda s: (-_rel_span(s) / EDIT_COST[s], p[s])), False),
        "numeric_set_points_first":
            (sorted(SLOTS, key=lambda s: (0 if _is_numeric(s) else 1, p[s])), False),
        "categorical_choices_first":
            (sorted(SLOTS, key=lambda s: (0 if not _is_numeric(s) else 1, p[s])), False),
        # "fix the window that is worst / nearest / heaviest first" -- needs the prose mechanism map
        "repair_worst_window_first": (_attr_priority_order("t", True), True),
        "repair_nearest_window_first": (_attr_priority_order("t", False), True),
        "repair_heaviest_window_first": (_attr_priority_order("wt", True), True),
    }
    for name, (order, _) in r.items():
        assert sorted(order) == sorted(SLOTS), f"ranking rule {name} is not a permutation"
    return r


# =================================================================================================
# 18 level-choice rules
# =================================================================================================
def _clamp(k: int, n: int) -> int:
    return int(min(max(k, 0), n - 1))


def level_rules() -> Dict[str, Tuple[Callable[[str], int], bool]]:
    """name -> (slot -> target level index, needs_author_reading)."""
    def step(d: int):
        return lambda s: _clamp(_idx(s) + d, _n(s))

    def textbook(mag: Optional[int], sign: int):
        def f(s: str) -> int:
            dirn = TEXTBOOK[s]
            if dirn is None:
                return _idx(s)                       # no ordinal reading -> leave it alone
            dirn *= sign
            if mag is None:                          # push it as far as the grid allows
                return (_n(s) - 1) if dirn > 0 else 0
            return _clamp(_idx(s) + dirn * mag, _n(s))
        return f

    r: Dict[str, Tuple[Callable[[str], int], bool]] = {}
    for m in (1, 2, 3):
        r[f"up_{m}_notch"] = (step(+m), False)
        r[f"down_{m}_notch"] = (step(-m), False)
    r["to_highest_level"] = (lambda s: _n(s) - 1, False)
    r["to_lowest_level"] = (lambda s: 0, False)
    r["to_grid_median"] = (lambda s: _clamp(int(round((_n(s) - 1) / 2)), _n(s)), False)
    r["to_far_end"] = (lambda s: (_n(s) - 1) if _idx(s) < (_n(s) - 1) / 2 else 0, False)
    r["one_toward_middle"] = (
        lambda s: _clamp(_idx(s) + (1 if _idx(s) < (_n(s) - 1) / 2 else -1), _n(s)), False)
    r["two_toward_middle"] = (
        lambda s: _clamp(_idx(s) + (2 if _idx(s) < (_n(s) - 1) / 2 else -2), _n(s)), False)
    r["next_level_cyclic"] = (lambda s: (_idx(s) + 1) % _n(s), False)
    r["textbook_1_notch"] = (textbook(1, +1), True)
    r["textbook_2_notch"] = (textbook(2, +1), True)
    r["textbook_to_extreme"] = (textbook(None, +1), True)
    r["anti_textbook_1_notch"] = (textbook(1, -1), True)
    r["anti_textbook_to_extreme"] = (textbook(None, -1), True)
    return r


# =================================================================================================
# execute one policy greedily until the change budget is exhausted
# =================================================================================================
def run_policy(order: List[str], rule: Callable[[str], int]) -> Tuple[List[Dict[str, Any]],
                                                                     List[str]]:
    """Return (the designs after each adopted change, the change log).

    The prefix list IS the five-round submission plan: round k submits the design that stands after
    the k-th adopted change. A change is skipped -- not abandoned -- when it is a no-op, when it does
    not fit the remaining budget, or when C3-C7 would refuse to run the batch, so the policy keeps
    spending down its priority list instead of stopping at the first obstacle.
    """
    design = dict(START)
    cost = 0
    prefixes: List[Dict[str, Any]] = []
    log: List[str] = []
    for slot in order:
        if cost >= BUDGET:
            break
        target = LEVELS[slot][rule(slot)]
        if target == design[slot]:
            continue
        if cost + EDIT_COST[slot] > BUDGET:
            continue
        cand = dict(design)
        cand[slot] = target
        if constraints(cand):
            continue
        design = cand
        cost += EDIT_COST[slot]
        prefixes.append(dict(design))
        log.append(f"{slot}: {START[slot]!r} -> {target!r} (cost {EDIT_COST[slot]})")
    return prefixes, log


def score_trajectory(designs: List[Dict[str, Any]], c: Dict[str, Any], start_eval) -> Dict[str, Any]:
    """The shipped graded path, exactly as src/main.py uses it."""
    evs = [evaluate_design(x, c["objective"]) for x in designs]
    fs = final_score(start_eval, evs, c["constraints"], c["scoring"], c["reference"])
    det = fs["optimality_score_details"]
    return {"total_score": int(fs["total_score"]),
            "achievement": det["achievement_fraction"],
            "best_usable_D": det.get("best_successful_objective"),
            "n_usable": int(fs["num_successful_designs"])}


def score_one(design: Dict[str, Any], c: Dict[str, Any], start_eval) -> Tuple[int, float, float]:
    """Score a single design as a one-round trajectory. Returns (points, achievement, D or nan)."""
    ev = evaluate_design(design, c["objective"])
    fs = final_score(start_eval, [ev], c["constraints"], c["scoring"], c["reference"])
    det = fs["optimality_score_details"]
    D = ev.desirability if ev.desirability is not None else float("nan")
    return int(fs["total_score"]), float(det["achievement_fraction"]), float(D)


def assert_uses_only_printed_data() -> None:
    """Rule 2 of the module docstring, enforced rather than promised.

    Every input the rule generators consume is re-derived here from `design_grid` -- the PUBLIC half
    of the ruler, which `scripts/leak_check_question.py` asserts is exactly what question.md prints --
    and from `PRINTED_BASELINE_RESPONSES`, which is transcribed from the question's own table. If a
    rule had reached into the response mechanism, one of these would not hold.
    """
    assert "agglomeration" not in sys.modules or True     # imported later only for the re-derivation
    for s in SLOTS:
        assert START[s] in LEVELS[s], f"{s}: the baseline set point is not on its printed grid"
        assert EDIT_COST[s] in (1, 2, 3), f"{s}: change cost is not one of the three printed tiers"
    assert sum(EDIT_COST.values()) == TOTAL_EDIT_COST == 22
    assert set(PRINTED_BASELINE_RESPONSES) == set(RESPONSE_KEYS)
    for a, ss in ATTR_SLOTS.items():
        assert a in RESPONSE_KEYS and all(s in SLOTS for s in ss)
    assert set(TEXTBOOK) == set(SLOTS)
    for s, d in TEXTBOOK.items():
        assert d in (None, +1, -1)
        assert (d is None) == (not _is_numeric(s) and s == "S1_bridging_liquid") or d is not None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=OUT)
    ap.add_argument("--top", type=int, default=10)
    args = ap.parse_args()

    t0 = time.time()
    assert_uses_only_printed_data()
    with open(TASK_CFG) as fh:
        c = yaml.safe_load(fh)
    n_rounds = int(c["iteration"]["max_rounds"])
    start_eval = evaluate_reference_start(c["objective"])
    D0 = float(start_eval.desirability)
    Dref = float(c["reference"]["best_objective_in_budget"])

    # The printed baseline table is not stale: the four values question.md prints round-trip to the
    # four the shipped simulator returns. Checked AFTER the rules were built, never before.
    printed_ok = {k: (round(float(start_eval.responses[k]), 4),
                      PRINTED_BASELINE_RESPONSES[k],
                      abs(float(start_eval.responses[k]) - PRINTED_BASELINE_RESPONSES[k]))
                  for k in RESPONSE_KEYS}
    stale = {k: v for k, v in printed_ok.items() if v[2] > 0.05 * max(1.0, abs(v[1])) * 0.01 + 0.06}
    print(f"baseline D = {D0:.9f}   reference D = {Dref:.9f}   budget = {BUDGET}/{TOTAL_EDIT_COST}"
          f"   rounds = {n_rounds}")
    print("printed baseline table vs the simulator: "
          + ", ".join(f"{k} {v[0]} vs {v[1]}" for k, v in printed_ok.items())
          + ("   STALE" if stale else "   consistent"))

    dist = baseline_window_distance()
    print("\nbaseline window position, from printed numbers only (this is what the 'repair ...' "
          "ranking rules see):")
    for k in RESPONSE_KEYS:
        print(f"   {k:<10s} {dist[k]['side']:<6s} t={dist[k]['t']:.3f}  d={dist[k]['d']:.4f}  "
              f"w={dist[k]['w']:.0f}  w*t={dist[k]['wt']:.3f}")

    orders, rules = slot_orders(), level_rules()
    print(f"\n{len(orders)} slot-ranking rules x {len(rules)} level rules = "
          f"{len(orders) * len(rules)} policies, each executed greedily to the budget")

    records: List[Dict[str, Any]] = []
    by_nchanged: Dict[int, Dict[str, Any]] = {}
    n_designs = 0
    for oname, (order, o_author) in orders.items():
        for lname, (rule, l_author) in rules.items():
            prefixes, log = run_policy(order, rule)
            if not prefixes:
                records.append({"policy": f"{oname} | {lname}", "n_changes": 0, "cost": 0,
                                "total_score": 0, "achievement": 0.0, "best_usable_D": None,
                                "uses_author_reading": bool(o_author or l_author),
                                "changes": [], "note": "the rule is a no-op on every variable"})
                continue
            traj = score_trajectory(prefixes[:n_rounds], c, start_eval)
            n_designs += len(prefixes[:n_rounds])
            rec = {"policy": f"{oname} | {lname}",
                   "ranking_rule": oname, "level_rule": lname,
                   "uses_author_reading": bool(o_author or l_author),
                   "n_changes": len(prefixes), "cost": edit_cost(prefixes[-1]),
                   "changes": log, **traj}
            records.append(rec)
            # per-design breakdown by how many variables the design moves -- the axis G1 cannot see
            for j, d in enumerate(prefixes[:n_rounds], start=1):
                pts, ach, D = score_one(d, c, start_eval)
                cur = by_nchanged.get(j)
                if cur is None or pts > cur["total_score"] or (pts == cur["total_score"]
                                                               and D > cur["D"]):
                    by_nchanged[j] = {"n_changed": j, "total_score": pts, "achievement": ach,
                                      "D": D, "cost": edit_cost(d),
                                      "policy": f"{oname} | {lname}",
                                      "uses_author_reading": bool(o_author or l_author),
                                      "changes": log[:j]}

    records.sort(key=lambda r: (-r["total_score"], -(r["best_usable_D"] or 0.0)))
    ceiling_all = max(r["total_score"] for r in records)
    no_author = [r for r in records if not r["uses_author_reading"]]
    ceiling_no_author = max(r["total_score"] for r in no_author)

    print(f"\ntop {args.top} policies (scored as five-round runs through the shipped scorer):")
    for r in records[:args.top]:
        tag = " [author reading]" if r["uses_author_reading"] else ""
        print(f"   {r['total_score']:>3d} pts  ach={r['achievement']:.4f}  "
              f"{r['n_changes']} vars, cost {r['cost']}  {r['policy']}{tag}")
        for ch in r["changes"]:
            print(f"            {ch}")

    print("\nbest score by NUMBER OF VARIABLES the design moves "
          "(gate G1 only ever sees 1 and 2):")
    for j in sorted(by_nchanged):
        b = by_nchanged[j]
        tag = " [author reading]" if b["uses_author_reading"] else ""
        print(f"   {j} variable(s): {b['total_score']:>3d} pts   ach={b['achievement']:.4f}   "
              f"cost {b['cost']}   {b['policy']}{tag}")
        for ch in b["changes"]:
            print(f"            {ch}")

    verdict = "PASS" if ceiling_all < NAIVE_THRESHOLD else "FAIL"
    print(f"\nnaive policy ceiling = {ceiling_all} / 100   [threshold < {NAIVE_THRESHOLD}]"
          f"   -> {verdict}")
