#!/usr/bin/env python
"""Designer-side derivation of the reference optimum and of the three difficulty gates.

Everything printed and written by this script comes from the SHIPPED graded path:

    src/evaluator.evaluate_design      -> the four responses + the desirability D
    src/evaluator.satisfies_all_constraints -> the feasibility predicate (C2-C7)
    src/scoring.final_score            -> achievement, the score bands, the 0-point gates
    src/design_space.iter_*            -> the mechanical enumerators
    tasks/q1_agglomeration/task_config.yaml -> the windows, the constraints, the bands

There is deliberately NO simplified twin of the objective anywhere in this file. Every problem in
this series that shipped a mis-calibrated instance did it the same way: a fast stand-in scored the
offline gates, the real evaluator scored the model, and the two quietly disagreed. So the gate numbers
here are produced by calling the same functions the harness calls, one design at a time, 1.2 ms each,
and the run is parallelised across processes rather than vectorised across designs.

For the same reason nothing is hand-listed. The "moves a competent chemist would try" set is
GENERATED by src/design_space.iter_k_slot_designs (every 1-slot, 2-slot and 3-slot change, each
auto-annotated "slot: from -> to"), and the change-budget neighbourhood is GENERATED by
iter_budget_designs. A hand-written move list only contains the moves the author thought of, which
confirms the design instead of testing it.

What is computed
----------------
  start_value      D of the registered process.
  reference_best   the EXACT maximum of D over the exhaustively enumerated change-budget
                   neighbourhood (every design with change cost <= BUDGET that satisfies C3-C7).
                   This is a bounded search in the strongest sense available: the bound is the whole
                   scorable region, so no heuristic search can beat it. It is not a claim of global
                   optimality over the 6.5e8-design gross space -- a design outside the budget cannot
                   score, so the gross space is irrelevant to the score.
  G1               best score over all 1-slot changes and all 2-slot changes.       must be < 50
  G2               best score over designs that are comfortably inside the budget:
                   change overlap >= floor + 0.05  <=>  cost <= design_space.g2_cost_criterion().
                   The margin is 0.05, and the same criterion is used to select and to accept --
                   filtering with one margin and accepting with another is how a sibling problem
                   shipped an instance the enumeration later scored at 63.                 must be < 50
  G3               number of feasible in-budget designs that strictly improve D on the registered
                   process (fairness: proof the score is not suppressed by a narrow region).
                                                                                    must be >= 50

Usage
-----
    python scripts/enumerate_reference_best.py [--workers 8] [--quick]

    --quick   restricts the enumeration to the 1/2/3-slot families and skips the full neighbourhood.
              Useful for a smoke test; it CANNOT establish the reference or G2/G3 and says so.

Writes answers/reference_enumeration.json (designer-only; never shown to the model, never in the
prompt). scripts/check_consistency.py reads that file and asserts task_config.yaml still agrees with
it, so the calibration is asserted rather than read.
"""
