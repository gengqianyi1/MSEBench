"""Generate the three organizer reports from immutable public evidence."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.runtime_support import load_json


PENDING_PACKAGE_GATE = "PENDING_FINAL_ARCHIVE_VALIDATION"
FINAL_PACKAGE_GATE = "FINAL_ARCHIVE_CLEAN_EXTRACTION_PASS"


def _write(path: Path, content: str) -> None:
    normalized = content.rstrip() + "\n"
    temporary = path.with_name(path.name + ".tmp")
    if temporary.exists():
        raise FileExistsError("report temporary file already exists")
    temporary.write_text(normalized, encoding="utf-8", newline="\n")
    temporary.replace(path)


def _mark(value: Any) -> str:
    return "PASS" if value is True else "FAIL" if value is False else str(value)


def design_report() -> str:
    return """# Benchmark Design Report

## Scope

This benchmark measures whether a tool-using agent can recover a failed local
xTB workflow through an auditable loop: inspect immutable evidence, distinguish
process state from scientific completion, select a provenance-safe restart,
execute native xTB through a fixed argv builder, react to validation feedback,
and finish both optimization and Hessian phases.

The frozen task is neutral closed-shell aspirin (21 atoms), GFN2-xTB, charge 0,
UHF 0, gas phase, geometry optimization followed by Hessian. `job_spec.json` is
the scientific authority; `configs/task.yaml` is the protocol, policy, budget,
runtime, model-registry, security, and scoring authority.

## Native initial failure and recoverability

The initial failure fixture was generated by xTB 6.7.1 with a one-cycle
optimization limit. The process exits at the execution layer, while the native
output states that geometry optimization failed to converge and supplies one
complete current trajectory frame. An independent regeneration receipt freezes
the same semantic conditions. Recovery is possible by preserving all scientific
invariants, using that last complete current frame (or the original input as a
lower-quality fallback), and increasing only the allowed optimization-cycle
budget.

## Stale-artifact trap

`legacy/xtbopt.xyz` is a real, chemically valid result from an independent
successful native optimization. Its manifest marks it as non-current and
unauthorized for restart or current-success evidence. This deliberately tests
whether an agent trusts filenames or verifies origin and currentness.

## Controlled tools and attempts

The model receives eleven strict structured tools and no shell, Python, network,
arbitrary file access, project source, credential, or evaluator access. Paths are
workspace-relative and normalized; parent, absolute, reparse-point, source, and
private-oracle access is rejected. `prepare_restart` creates immutable numbered
attempts, while `run_xtb` reconstructs a fixed conda wrapper plus scientific argv
and verifies the configured xTB identity. Each attempt retains canonical command,
input, stdout/stderr, execution, provenance, manifest, and validation records.

## Evaluation and scoring

The public evaluator does not call an LLM or xTB. It independently re-derives
lifecycle, hash-chain integrity, exact model metadata, tool and attempt budgets,
argv invariants, source provenance, log facts, XYZ validity, optimization
convergence, Hessian completion, and final-artifact currentness. The fixed rubric
is 25 diagnosis/evidence + 25 restart/provenance + 30 recovery + 10 feedback loop
+ 10 compliance/efficiency = 100. A failed eligibility gate makes the official
score zero while retaining the diagnostic ungated score.

## Replay versus live

`REPLAY` never calls an API or xTB and must reproduce `evaluation.json` byte for
byte from frozen public evidence. `LIVE_XTB` executes native xTB in an isolated
workspace. Formal trajectories must additionally be `REAL_API`, use the exact
configured SiliconFlow model, and contain provider request IDs and exact response
model metadata. A SHA-256 event chain proves internal consistency; it is not a
cryptographic provider-identity signature.

## Security boundaries and limitations

Credentials are loaded only at runtime from the exact parent `.env` with
`override=False`; their value, length, prefix, suffix, and hash are never
persisted. Provider exceptions are reduced to non-reflective types/statuses.
Hidden reasoning and raw provider responses are excluded. The public package
excludes the private oracle, local runs, failed runs, caches, staging, and all
credentials. Native runtime receipts bind the configured executable/version/help
hash on this platform, but reproducibility on another platform requires a trusted
xTB 6.7.1 installation matching its own frozen configuration.
"""


def validation_report(release: dict[str, Any], package_gate: str) -> str:
    gates = release["gates"]
    tests = gates["tests"]
    groups = tests["groups"]
    native = gates["native_xtb"]
    scan = gates["security_and_path_scan"]
    configuration = gates["configuration"]
    baseline = gates["baseline"]
    rows = []
    for name in ("unit", "integration", "security", "e2e"):
        item = groups[name]
        rows.append(
            f"| {name} | {item['passed_count']} | {item['skipped_count']} | "
            f"{item['failed_count']} | {item['error_count']} | {_mark(item['passed'])} |"
        )
    return f"""# Organizer Validation Report

## Delivery state

- Project root inside the archive: `.`
- Task: `xtb_failure_diagnosis_restart_agent_v1`
- Release status: `{release['status']}`
- Python: `{release['python_version']}`
- xTB executable status: `{native['xtb'].get('status', 'UNKNOWN')}`
- xTB version: `{native['xtb'].get('version', 'UNKNOWN')}`
- Config conflict: `{not configuration['passed']}`

## Native evidence

- Initial failure generated by native xTB: `{native['initial_failure_native']}`
- Initial optimization cycle limit: `{native['initial_failure_cycle_limit']}`
- Independent failure regeneration: `{_mark(native['initial_failure_regenerated'])}`
- Independent successful optimization receipt: `{_mark(native['successful_optimization_verified'])}`
- Native Hessian smoke: `{_mark(native['hessian_verified'])}`
- Live deterministic baseline: `{_mark(baseline['passed'])}`
- Baseline official score: `{baseline['official_score']}`
- Baseline evaluator replay byte-identical: `{_mark(baseline['evaluation_byte_identical'])}`

## Tests

| Group | Passed | Skipped | Failed | Errors | Status |
| --- | ---: | ---: | ---: | ---: | --- |
{chr(10).join(rows)}

Total: {tests['total_passed']} passed, {tests['total_skipped']} skipped,
{tests['total_failed']} failed, {tests['total_errors']} errors.

## Security and packaging

- Package-scope secret findings: `{scan['secret_finding_count']}`
- Package-scope runtime absolute-path findings: `{scan['runtime_absolute_path_finding_count']}`
- Expected path literals confined to security tests: `{scan['expected_security_test_path_literal_count']}`
- Package clean-extraction result: `{_mark(package_gate == FINAL_PACKAGE_GATE)}`
- Package gate state recorded in this release snapshot: `{package_gate}`
- Final archive identity and exact-byte clean-extraction receipt are recorded in
  the external `ORGANIZER_SUBMISSION_CHECKLIST.md` and `.sha256` sidecar, avoiding
  a self-referential ZIP hash.

## Final status

`{release['status']}`
"""


def comparison_report(release: dict[str, Any]) -> str:
    rows = []
    for logical in ("kimi", "deepseek", "glm"):
        model = release["models"][logical]
        rows.append(
            "| {logical} | `{requested}` | `{actual}` | {provider} | {mode} + {native} | "
            "{tools} | {attempts} | {opt} | {hess} | {score} | {replay} | `{trace}` | {status} |".format(
                logical=logical,
                requested=model["requested_model"],
                actual=model.get("actual_model") or "MISSING",
                provider=model.get("provider") or "MISSING",
                mode=model.get("execution_mode") or "MISSING",
                native=model.get("native_mode") or "MISSING",
                tools=model.get("tool_calls", 0),
                attempts=model.get("xtb_attempts", 0),
                opt=_mark(model.get("optimization_completed")),
                hess=_mark(model.get("hessian_completed")),
                score=model.get("official_score", 0),
                replay=_mark(model.get("replay_byte_identical")),
                trace=model.get("trajectory_sha256") or "MISSING",
                status=model.get("status", "MISSING"),
            )
        )
    return f"""# Organizer Model Comparison

All three entries below are independently replayed public trajectories. Exact
identity means the provider response `model` field matched the configured request
on every successful response and a provider request ID was present. This is
auditable response metadata, not a cryptographic identity proof.

| Logical model | Exact requested model | Exact actual model | Provider | Execution | Tool calls | xTB attempts | Optimization | Hessian | Score | Replay | Trajectory SHA-256 | Status |
| --- | --- | --- | --- | --- | ---: | ---: | --- | --- | ---: | --- | --- | --- |
{chr(10).join(rows)}

No model fallback or model-name substitution is permitted. Each formal run uses
its own clone of the frozen case and its own native xTB artifacts.
"""


def generate_reports(
    root: Path,
    release: dict[str, Any],
    *,
    package_gate: str,
) -> dict[str, Any]:
    """Render reports for a provisional source or a transactional final payload."""

    status = release.get("status") if isinstance(release, dict) else None
    allowed = {
        ("READY_FOR_PACKAGE", PENDING_PACKAGE_GATE),
        ("PASS", FINAL_PACKAGE_GATE),
    }
    if (status, package_gate) not in allowed:
        raise ValueError("RELEASE_AND_PACKAGE_GATE_STATE_MISMATCH")
    reports = root / "reports"
    reports.mkdir(exist_ok=True)
    _write(reports / "BENCHMARK_DESIGN_REPORT.md", design_report())
    _write(
        reports / "ORGANIZER_VALIDATION_REPORT.md",
        validation_report(release, package_gate),
    )
    _write(
        reports / "ORGANIZER_MODEL_COMPARISON.md",
        comparison_report(release),
    )
    return {"status": status, "package_gate": package_gate, "report_count": 3}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate organizer reports")
    parser.add_argument(
        "--package-gate",
        default=PENDING_PACKAGE_GATE,
        choices=[
            PENDING_PACKAGE_GATE,
            FINAL_PACKAGE_GATE,
        ],
    )
    args = parser.parse_args(argv)
    release_path = ROOT / "configs" / "release.json"
    release = load_json(release_path)
    if not isinstance(release, dict):
        print(json.dumps({"status": "BLOCKED", "error": "RELEASE_INVALID"}, sort_keys=True))
        return 1
    try:
        result = generate_reports(ROOT, release, package_gate=args.package_gate)
    except (FileExistsError, OSError, ValueError) as exc:
        print(
            json.dumps(
                {"status": "BLOCKED", "error": str(exc)},
                ensure_ascii=True,
                sort_keys=True,
            )
        )
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
